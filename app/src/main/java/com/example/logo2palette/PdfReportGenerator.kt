    fun createReport(
        context: Context,
        logo: Bitmap,
        palette: ColorPalette,
        paletteNumber: Int
    ): File {

        val document = PdfDocument()

        // =========================================================
        // PAGE 1: Brand Identity & Swatches
        // =========================================================
        val pageInfo1 = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page1 = document.startPage(pageInfo1)
        val canvas1 = page1.canvas
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        drawPageHeader(canvas1, paint, "Brand Color System", paletteNumber)
        drawLogoSection(canvas1, paint, logo)
        drawSwatchesSection(canvas1, paint, palette)
        drawCodeTokensSummary(canvas1, paint, palette)
        drawFooter(canvas1, paint, 1, 2)
        document.finishPage(page1)

        // =========================================================
        // PAGE 2: Website UI & Mobile App UI Mockup Previews
        // =========================================================
        val pageInfo2 = PdfDocument.PageInfo.Builder(595, 842, 2).create()
        val page2 = document.startPage(pageInfo2)
        val canvas2 = page2.canvas

        drawPageHeader(canvas2, paint, "UI Previews & Mockups", paletteNumber)
        drawWebsitePreviewSection(canvas2, paint, palette, 40f, 90f)
        drawMobilePreviewSection(canvas2, paint, palette, 40f, 420f)
        drawFooter(canvas2, paint, 2, 2)
        document.finishPage(page2)

        // Save PDF to cache directory
        val directory = File(context.cacheDir, "reports")
        if (!directory.exists()) directory.mkdirs()

        val file = File(directory, "Logo2Palette_Brand_Report.pdf")
        FileOutputStream(file).use { output ->
            document.writeTo(output)
        }
        document.close()

        return file
    }

