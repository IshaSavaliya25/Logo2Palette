    private fun drawPageHeader(canvas: Canvas, paint: Paint, subtitle: String, paletteNumber: Int) {
        canvas.drawColor(Color.WHITE)

        // Top Accent Bar
        paint.color = Color.rgb(103, 80, 164)
        canvas.drawRect(0f, 0f, 595f, 8f, paint)

        // Title
        paint.color = Color.rgb(28, 27, 31)
        paint.textSize = 24f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("Logo2Palette", 40f, 45f, paint)

        // Subtitle
        paint.color = Color.rgb(111, 107, 118)
        paint.textSize = 12f
        paint.typeface = Typeface.DEFAULT
        canvas.drawText(subtitle, 40f, 64f, paint)

        // Palette Number Pill
        paint.color = Color.rgb(238, 235, 244)
        canvas.drawRoundRect(450f, 30f, 555f, 60f, 15f, 15f, paint)

        paint.color = Color.rgb(103, 80, 164)
        paint.textSize = 11f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("Palette #$paletteNumber", 465f, 49f, paint)

        // Divider Line
        paint.color = Color.rgb(230, 230, 235)
        canvas.drawLine(40f, 75f, 555f, 75f, paint)
    }

    private fun drawFooter(canvas: Canvas, paint: Paint, pageNum: Int, totalPages: Int) {
        paint.color = Color.rgb(230, 230, 235)
        canvas.drawLine(40f, 805f, 555f, 805f, paint)

        paint.color = Color.rgb(140, 140, 145)
        paint.textSize = 10f
        paint.typeface = Typeface.DEFAULT
        canvas.drawText("Generated by Logo2Palette • Smart Web & Mobile Color System", 40f, 822f, paint)
        canvas.drawText("Page $pageNum of $totalPages", 500f, 822f, paint)
    }

    // =========================================================
    // LOGO & SWATCHES (PAGE 1)
    // =========================================================

    private fun drawLogoSection(canvas: Canvas, paint: Paint, logo: Bitmap) {
        paint.color = Color.rgb(28, 27, 31)
        paint.textSize = 14f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("BRAND LOGO SOURCE", 40f, 100f, paint)

        // Card frame around logo
        paint.color = Color.rgb(248, 247, 252)
        canvas.drawRoundRect(40f, 110f, 555f, 220f, 16f, 16f, paint)

        val softwareLogo = if (logo.config == Bitmap.Config.HARDWARE) {
            logo.copy(Bitmap.Config.ARGB_8888, false)
        } else logo

        val maxDimension = 90f
        val ratio = minOf(maxDimension / softwareLogo.width, maxDimension / softwareLogo.height)
        val logoWidth = softwareLogo.width * ratio
        val logoHeight = softwareLogo.height * ratio
        val logoLeft = (595f - logoWidth) / 2f
        val logoTop = 110f + (110f - logoHeight) / 2f

        canvas.drawBitmap(
            softwareLogo,
            null,
            RectF(logoLeft, logoTop, logoLeft + logoWidth, logoTop + logoHeight),
            paint
        )
    }

    private fun drawSwatchesSection(canvas: Canvas, paint: Paint, palette: ColorPalette) {
        paint.color = Color.rgb(28, 27, 31)
        paint.textSize = 14f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("EXTRACTED DESIGN TOKENS & WCAG RATIOS", 40f, 245f, paint)

        val swatches = listOf(
            Triple("PRIMARY", palette.primary, palette.onPrimary),
            Triple("SECONDARY", palette.secondary, palette.onSecondary),
            Triple("ACCENT", palette.accent, palette.onAccent),
            Triple("BACKGROUND", palette.background, palette.onBackground),
            Triple("SURFACE", palette.surface, palette.onSurface),
            Triple("TEXT PRIMARY", palette.textPrimary, palette.background)
        )

        var xPos = 40f
        var yPos = 260f

        swatches.forEachIndexed { index, (role, hex, contrastTarget) ->
            if (index > 0 && index % 2 == 0) {
                xPos = 40f
                yPos += 75f
            } else if (index % 2 == 1) {
                xPos = 300f
            }

            drawPdfSwatchCard(canvas, paint, role, hex, xPos, yPos)
        }
    }

    private fun drawPdfSwatchCard(
        canvas: Canvas,
        paint: Paint,
        role: String,
        hex: String,
        x: Float,
        y: Float
    ) {
        val color = try { Color.parseColor(hex) } catch (e: Exception) { Color.GRAY }
        val textColorInt = ColorUtils.getContrastTextColor(color)
        val ratio = ColorUtils.calculateContrastRatio(textColorInt, color)
        val badge = ColorUtils.getWcagBadge(ratio)

        // Card Container Background
        paint.color = Color.rgb(250, 250, 252)
        canvas.drawRoundRect(x, y, x + 250f, y + 65f, 12f, 12f, paint)

        // Color Swatch Circle
        paint.color = color
        canvas.drawRoundRect(x + 10f, y + 10f, x + 55f, y + 55f, 12f, 12f, paint)

        // Role Label
        paint.color = Color.rgb(28, 27, 31)
        paint.textSize = 12f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText(role, x + 65f, y + 26f, paint)

        // HEX & WCAG Rating
        paint.color = Color.rgb(110, 110, 120)
        paint.textSize = 10f
        paint.typeface = Typeface.DEFAULT
        canvas.drawText("$hex  •  $badge", x + 65f, y + 46f, paint)
    }

    private fun drawCodeTokensSummary(canvas: Canvas, paint: Paint, palette: ColorPalette) {
        val startY = 500f
        paint.color = Color.rgb(28, 27, 31)
        paint.textSize = 14f
        paint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("DEVELOPER CODE EXPORT SNIPPET", 40f, startY, paint)

        // Dark Code Container
        paint.color = Color.rgb(30, 30, 36)
        canvas.drawRoundRect(40f, startY + 15f, 555f, startY + 280f, 16f, 16f, paint)

        paint.color = Color.rgb(160, 230, 160)
        paint.textSize = 11f
        paint.typeface = Typeface.MONOSPACE

        val cssLines = ColorUtils.toCssVariables(palette).split("\n")
        var lineY = startY + 40f
        cssLines.forEach { line ->
            if (lineY < startY + 270f) {
                canvas.drawText(line, 55f, lineY, paint)
                lineY += 16f
            }
        }
    }

